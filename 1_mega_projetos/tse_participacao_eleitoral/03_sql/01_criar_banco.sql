CREATE DATABASE IF NOT EXISTS tse_participacao
  CHARACTER SET utf8mb4;

USE tse_participacao;

CREATE TABLE IF NOT EXISTS presidente_munzona (
  NR_TURNO TINYINT NOT NULL,
  SG_UF CHAR(2) NOT NULL,
  CD_MUNICIPIO INT NOT NULL,
  NM_MUNICIPIO VARCHAR(100),
  NR_ZONA SMALLINT NOT NULL,
  DS_CARGO VARCHAR(30),
  QT_APTOS INT,
  QT_COMPARECIMENTO INT,
  QT_ABSTENCOES INT,
  ST_VOTO_EM_TRANSITO CHAR(1),
  QT_BRANCOS INT,
  QT_NULOS INT,
  QT_ELEITORES_SECOES_NAO_INSTALADAS INT,
  PRIMARY KEY (NR_TURNO, SG_UF, CD_MUNICIPIO, NR_ZONA)
);

